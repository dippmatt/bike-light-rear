#!/usr/bin/env python3
"""Precompute a run of a real AirTag's rotating keys for the firmware (ADR-0012).

The light has no RTC and no persistent flash, so it cannot compute Apple's real
15-minute key schedule live. This generates the next COUNT private keys
starting at the index "now" maps to, as a flat table the firmware advances
through on its own uptime clock. It always uses the PRIMARY chain (what an
AirTag broadcasts while not in "separated"/lost mode); Apple's servers decrypt
reports from it the same way regardless.

The table goes stale after COUNT * 15 minutes and needs a fresh run + reflash.

Needs: pip install findmy (same venv as track.py)

Usage:
  gen_airtag_table.py ACCESSORY.json [--out DIR] [--count N]

  ACCESSORY.json  a single FindMyAccessory, as saved by os-findmy-e's
                  tools/machoadi/tag_keys.py --tags-save (one entry picked out)
  --out DIR       firmware src/ directory for the generated .c/.h
                  (default: ../../src, i.e. software/rear_light_ant/src)
  --count N       number of 15-minute slots (default 672 = 1 week)
"""

from __future__ import annotations

import argparse
import datetime
import json
import sys
from pathlib import Path

DEFAULT_OUT = Path(__file__).resolve().parents[2] / "src"
HERE = Path(__file__).resolve().parent


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("accessory", type=Path)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--count", type=int, default=672)
    args = ap.parse_args()

    from findmy.accessory import FindMyAccessory

    acc = FindMyAccessory.from_json(args.accessory)
    now = datetime.datetime.now(datetime.timezone.utc)
    start_index = acc.get_max_index(now)

    # No public single-key accessor exists for "primary only" (keys_at() mixes in
    # secondary candidates for a report's ambiguity window, which we don't want
    # for broadcasting). _primary_key_at is the primary chain's own generator,
    # pinned to this findmy commit (see tools/haystack/README.md).
    # The firmware broadcasts these, so they must be the advertised (public, x
    # coordinate) keys, never the private scalars.
    keys = [acc._primary_key_at(start_index + i).adv_key_bytes for i in range(args.count)]  # noqa: SLF001
    key_len = len(keys[0])
    assert all(len(k) == key_len for k in keys)

    args.out.mkdir(parents=True, exist_ok=True)
    h_path = args.out / "airtag_table.h"
    c_path = args.out / "airtag_table.c"

    h_path.write_text(
        "/* GENERATED by tools/haystack/gen_airtag_table.py. Contains derived key\n"
        " * material: never commit (see .gitignore). */\n\n"
        "#ifndef AIRTAG_TABLE_H\n#define AIRTAG_TABLE_H\n\n#include <stdint.h>\n\n"
        f"#define AIRTAG_KEY_LEN {key_len}U\n"
        f"#define AIRTAG_TABLE_COUNT {len(keys)}U\n\n"
        "extern const uint8_t airtag_table[AIRTAG_TABLE_COUNT][AIRTAG_KEY_LEN];\n\n"
        "#endif /* AIRTAG_TABLE_H */\n"
    )

    with c_path.open("w") as f:
        f.write(
            "/* GENERATED by tools/haystack/gen_airtag_table.py. Contains derived key\n"
            " * material: never commit (see .gitignore). */\n\n"
            '#include "airtag_table.h"\n\n'
            "const uint8_t airtag_table[AIRTAG_TABLE_COUNT][AIRTAG_KEY_LEN] = {\n"
        )
        for k in keys:
            f.write("    {" + ",".join(f"0x{b:02x}" for b in k) + "},\n")
        f.write("};\n")

    covers_until = now + datetime.timedelta(minutes=15 * len(keys))
    meta = {
        "name": acc.name,
        "generated_at": now.isoformat(),
        "start_index": start_index,
        "count": len(keys),
        "interval_minutes": 15,
        "covers_until": covers_until.isoformat(),
    }
    meta_path = HERE / "data" / f"airtag_table_{(acc.name or 'tag').lower()}.json"
    meta_path.parent.mkdir(exist_ok=True)
    meta_path.write_text(json.dumps(meta, indent=2))

    print(f"wrote {len(keys)} keys ({key_len} bytes each) to {c_path}")
    print(f"covers {meta['generated_at']}  ..  {meta['covers_until']}")
    print(f"metadata (no secrets): {meta_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

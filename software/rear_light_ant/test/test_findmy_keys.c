int main(void)
{
    uint8_t sk[FINDMY_SK_LEN];
    uint8_t adv[FINDMY_ADV_KEY_LEN];
    uint32_t i;

    /* Indices 0..3: SK_0 is SKN itself, each step one "update" */
    memcpy(sk, skn, sizeof(sk));
    for (i = 0U; i < 4U; i++) {
        CHECK(findmy_adv_key(master, sk, adv));
        CHECK(memcmp(adv, want_adv[i], sizeof(adv)) == 0);
        findmy_next_sk(sk, sk); /* in place, as the firmware does */
    }

    /* A long chain stays on track */
    for (; i < 1000U; i++) {
        findmy_next_sk(sk, sk);
    }
    CHECK(memcmp(sk, want_sk1000, sizeof(sk)) == 0);
    CHECK(findmy_adv_key(master, sk, adv));
    CHECK(memcmp(adv, want_adv1000, sizeof(adv)) == 0);

    /* Backup chain: same functions, started from SKS */
    memcpy(sk, sks, sizeof(sk));
    findmy_next_sk(sk, sk);
    CHECK(memcmp(sk, want_sks1, sizeof(sk)) == 0);
    CHECK(findmy_adv_key(master, sk, adv));
    CHECK(memcmp(adv, want_sadv1, sizeof(adv)) == 0);
    for (i = 1U; i < 11U; i++) {
        findmy_next_sk(sk, sk);
    }
    CHECK(findmy_adv_key(master, sk, adv));
    CHECK(memcmp(adv, want_sadv11, sizeof(adv)) == 0);

    /* Index mapping: the lower of FindMy.py's two candidates */
    CHECK(findmy_secondary_index(1000U) == 11U);
    CHECK(findmy_secondary_index(0U) == 1U);
    CHECK(findmy_secondary_index(95U) == 1U);
    CHECK(findmy_secondary_index(96U) == 2U);

    /* A master that is not on the curve is refused and leaves adv alone */
    {
        uint8_t bad[FINDMY_MASTER_LEN];

        memcpy(bad, master, sizeof(bad));
        bad[FINDMY_MASTER_LEN - 1U] ^= 0x01U;
        memset(adv, 0x5A, sizeof(adv));
        CHECK(!findmy_adv_key(bad, sk, adv));
        CHECK(adv[0] == 0x5AU && adv[FINDMY_ADV_KEY_LEN - 1U] == 0x5AU);
    }

    if (failures != 0) {
        printf("test_findmy_keys: %d failure(s)\n", failures);
        return 1;
    }
    printf("test_findmy_keys: all passed\n");
    return 0;
}
